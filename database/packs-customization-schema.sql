-- Executar UMA vez no schema MabjaiaInn (SQL Developer), ANTES de arrancar a API.
-- O projecto usa spring.jpa.hibernate.ddl-auto=validate, por isso estas estruturas tem de existir.
--
-- NOTA: as colunas booleanas abaixo usam NUMBER(1), o mesmo que o Hibernate costuma usar no Oracle.
-- Confirme com a coluna PACKS.PACK_AC: se ela for do tipo BOOLEAN (Oracle 23ai), troque NUMBER(1) por BOOLEAN
-- (e os valores DEFAULT 1 / 0 por TRUE / FALSE).

-- 1) Novas colunas nas estadias existentes
ALTER TABLE PACKS ADD (
    PACK_DESCRIPTION VARCHAR2(500 CHAR),
    PACK_CUSTOM      NUMBER(1) DEFAULT 0 NOT NULL
);

-- 2) Extras configuraveis (ar condicionado, piscina, atendimento VIP...)
CREATE SEQUENCE PACK_FEATURE_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE PACK_FEATURE (
    FEATURE_ID  NUMBER(19,0)       NOT NULL,
    CODE        VARCHAR2(40 CHAR)  NOT NULL,
    NAME        VARCHAR2(80 CHAR)  NOT NULL,
    DESCRIPTION VARCHAR2(200 CHAR),
    PRICE       NUMBER(19,2)       NOT NULL,
    ACTIVE      NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT PK_PACK_FEATURE PRIMARY KEY (FEATURE_ID),
    CONSTRAINT UK_PACK_FEATURE_CODE UNIQUE (CODE)
);

-- 3) Extras incluidos em cada estadia
CREATE TABLE PACK_FEATURE_LINK (
    PACK_ID    NUMBER(19,0) NOT NULL,
    FEATURE_ID NUMBER(19,0) NOT NULL,
    CONSTRAINT PK_PACK_FEATURE_LINK PRIMARY KEY (PACK_ID, FEATURE_ID),
    CONSTRAINT FK_PFL_PACK    FOREIGN KEY (PACK_ID)    REFERENCES PACKS (PACK_ID),
    CONSTRAINT FK_PFL_FEATURE FOREIGN KEY (FEATURE_ID) REFERENCES PACK_FEATURE (FEATURE_ID)
);

-- 4) Historico de estadias personalizadas de cada cliente
CREATE SEQUENCE CUSTOM_PACKAGE_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE CUSTOM_PACKAGE (
    CUSTOM_ID    NUMBER(19,0)      NOT NULL,
    CLIENT_ID    NUMBER(19,0)      NOT NULL,
    NAME         VARCHAR2(60 CHAR) NOT NULL,
    DURATION     NUMBER(10,0)      NOT NULL,
    LAST_PRICE   NUMBER(19,2),
    USE_COUNT    NUMBER(10,0) DEFAULT 0 NOT NULL,
    CREATED_AT   TIMESTAMP(6)      NOT NULL,
    LAST_USED_AT TIMESTAMP(6),
    CONSTRAINT PK_CUSTOM_PACKAGE PRIMARY KEY (CUSTOM_ID),
    CONSTRAINT FK_CUSTOM_PKG_CLIENT FOREIGN KEY (CLIENT_ID) REFERENCES CLIENT (CLIENT_ID)
);

CREATE TABLE CUSTOM_PACKAGE_FEATURE (
    CUSTOM_ID  NUMBER(19,0) NOT NULL,
    FEATURE_ID NUMBER(19,0) NOT NULL,
    CONSTRAINT PK_CUSTOM_PKG_FEATURE PRIMARY KEY (CUSTOM_ID, FEATURE_ID),
    CONSTRAINT FK_CPF_CUSTOM  FOREIGN KEY (CUSTOM_ID)  REFERENCES CUSTOM_PACKAGE (CUSTOM_ID),
    CONSTRAINT FK_CPF_FEATURE FOREIGN KEY (FEATURE_ID) REFERENCES PACK_FEATURE (FEATURE_ID)
);

CREATE INDEX IX_CUSTOM_PKG_CLIENT ON CUSTOM_PACKAGE (CLIENT_ID);
