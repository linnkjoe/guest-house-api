-- Allow Admin/Gestor to start a conversation and record who sent its first message.
ALTER TABLE CONTACT_MESSAGE ADD (
    SENDER_USERNAME VARCHAR2(100 CHAR),
    SENDER_ROLE     VARCHAR2(20 CHAR)
);

UPDATE CONTACT_MESSAGE message
   SET SENDER_USERNAME = (
           SELECT LOWER(client.CLIENT_EMAIL)
             FROM CLIENT client
            WHERE client.CLIENT_ID = message.CLIENT_ID
       ),
       SENDER_ROLE = 'CLIENTE'
 WHERE SENDER_ROLE IS NULL;

ALTER TABLE CONTACT_MESSAGE MODIFY (
    SENDER_USERNAME NOT NULL,
    SENDER_ROLE NOT NULL
);

ALTER TABLE CONTACT_MESSAGE ADD CONSTRAINT CK_CONTACT_MESSAGE_SENDER_ROLE
    CHECK (SENDER_ROLE IN ('ADMIN', 'GESTOR', 'CLIENTE'));

COMMIT;
