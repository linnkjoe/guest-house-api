CREATE SEQUENCE CONTACT_MESSAGE_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE CONTACT_MESSAGE (
    MESSAGE_ID   NUMBER(19,0)       NOT NULL,
    CLIENT_ID    NUMBER(19,0)       NOT NULL,
    SUBJECT      VARCHAR2(120 CHAR) NOT NULL,
    MESSAGE_TEXT VARCHAR2(2000 CHAR) NOT NULL,
    CREATED_AT   TIMESTAMP(6)       NOT NULL,
    REPLY_TEXT   VARCHAR2(2000 CHAR),
    REPLIED_BY   VARCHAR2(100 CHAR),
    REPLIED_AT   TIMESTAMP(6),
    CONSTRAINT PK_CONTACT_MESSAGE PRIMARY KEY (MESSAGE_ID),
    CONSTRAINT FK_CONTACT_MESSAGE_CLIENT FOREIGN KEY (CLIENT_ID) REFERENCES CLIENT (CLIENT_ID)
);

CREATE INDEX IX_CONTACT_MESSAGE_CREATED
    ON CONTACT_MESSAGE (CREATED_AT DESC);

CREATE INDEX IX_CONTACT_MESSAGE_CLIENT
    ON CONTACT_MESSAGE (CLIENT_ID, CREATED_AT DESC);
