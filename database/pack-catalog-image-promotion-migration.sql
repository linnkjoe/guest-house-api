-- Executar uma vez no schema da aplicacao antes de arrancar a versao atualizada.
ALTER TABLE PACKS ADD (
    REQUEST_COUNT       NUMBER(19,0) DEFAULT 0 NOT NULL,
    PROMOTION_DISCOUNT NUMBER(5,2) DEFAULT 0 NOT NULL,
    IMAGE_CONTENT_TYPE VARCHAR2(50 CHAR)
);

CREATE TABLE PACK_IMAGE (
    PACK_ID    NUMBER(19,0) NOT NULL,
    IMAGE_DATA BLOB         NOT NULL,
    CONSTRAINT PK_PACK_IMAGE PRIMARY KEY (PACK_ID),
    CONSTRAINT FK_PACK_IMAGE_PACK FOREIGN KEY (PACK_ID) REFERENCES PACKS (PACK_ID)
);

UPDATE PACKS p
SET REQUEST_COUNT = (
    SELECT COUNT(*)
    FROM BOOKING b
    WHERE b.PACK_ID = p.PACK_ID
);

ALTER TABLE PACKS ADD CONSTRAINT CK_PACKS_REQUEST_COUNT
    CHECK (REQUEST_COUNT >= 0);

ALTER TABLE PACKS ADD CONSTRAINT CK_PACKS_PROMO_DISCOUNT
    CHECK (PROMOTION_DISCOUNT BETWEEN 0 AND 90);
