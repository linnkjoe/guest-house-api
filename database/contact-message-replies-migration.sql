-- Add conversation replies to existing contact message subjects.
CREATE SEQUENCE CONTACT_MESSAGE_REPLY_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE CONTACT_MESSAGE_REPLY (
    REPLY_ID        NUMBER(19,0)       NOT NULL,
    MESSAGE_ID      NUMBER(19,0)       NOT NULL,
    SENDER_USERNAME VARCHAR2(100 CHAR) NOT NULL,
    SENDER_ROLE     VARCHAR2(20 CHAR)  NOT NULL,
    REPLY_TEXT      VARCHAR2(2000 CHAR) NOT NULL,
    CREATED_AT      TIMESTAMP(6)       NOT NULL,
    CONSTRAINT PK_CONTACT_MESSAGE_REPLY PRIMARY KEY (REPLY_ID),
    CONSTRAINT FK_CONTACT_MESSAGE_REPLY_MESSAGE
        FOREIGN KEY (MESSAGE_ID) REFERENCES CONTACT_MESSAGE (MESSAGE_ID),
    CONSTRAINT CK_CONTACT_MESSAGE_REPLY_ROLE
        CHECK (SENDER_ROLE IN ('ADMIN', 'GESTOR', 'CLIENTE'))
);

CREATE INDEX IX_CONTACT_MESSAGE_REPLY_THREAD
    ON CONTACT_MESSAGE_REPLY (MESSAGE_ID, CREATED_AT, REPLY_ID);

-- Preserve the first replies created by the previous single-response model.
INSERT INTO CONTACT_MESSAGE_REPLY (
    REPLY_ID, MESSAGE_ID, SENDER_USERNAME, SENDER_ROLE, REPLY_TEXT, CREATED_AT
)
SELECT CONTACT_MESSAGE_REPLY_SEQ.NEXTVAL,
       message.MESSAGE_ID,
       message.REPLIED_BY,
       COALESCE(app_user.USER_ROLE, 'GESTOR'),
       message.REPLY_TEXT,
       message.REPLIED_AT
  FROM CONTACT_MESSAGE message
  LEFT JOIN APP_USER app_user
    ON LOWER(app_user.USERNAME) = LOWER(message.REPLIED_BY)
 WHERE message.REPLY_TEXT IS NOT NULL
   AND message.REPLIED_AT IS NOT NULL
   AND message.REPLIED_BY IS NOT NULL;

COMMIT;
