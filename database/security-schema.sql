CREATE SEQUENCE APP_USER_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE APP_USER (
    USER_ID        NUMBER(19,0)        NOT NULL,
    USERNAME       VARCHAR2(100 CHAR)  NOT NULL,
    PASSWORD_HASH  VARCHAR2(100 CHAR)  NOT NULL,
    DISPLAY_NAME   VARCHAR2(100 CHAR),
    USER_ROLE      VARCHAR2(20 CHAR)   NOT NULL,
    ACCOUNT_ENABLED NUMBER(1,0) DEFAULT 1 NOT NULL,
    MUST_CHANGE_PASSWORD NUMBER(1,0) DEFAULT 0 NOT NULL,
    CLIENT_ID      NUMBER(19,0),
    CONSTRAINT PK_APP_USER        PRIMARY KEY (USER_ID),
    CONSTRAINT UK_APP_USER_NAME   UNIQUE (USERNAME),
    CONSTRAINT UK_APP_USER_CLIENT UNIQUE (CLIENT_ID),
    CONSTRAINT FK_APP_USER_CLIENT FOREIGN KEY (CLIENT_ID) REFERENCES CLIENT (CLIENT_ID),
    CONSTRAINT CK_APP_USER_ROLE   CHECK (USER_ROLE IN ('ADMIN', 'GESTOR', 'CLIENTE')),
    CONSTRAINT CK_APP_USER_ENABLED CHECK (ACCOUNT_ENABLED IN (0, 1)),
    CONSTRAINT CK_APP_USER_PASSWORD_CHANGE CHECK (MUST_CHANGE_PASSWORD IN (0, 1))
);
